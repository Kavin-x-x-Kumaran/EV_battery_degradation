"""
Turn an exported edge model (outputs/edge_model_<cell>.json) into a C header
that edge/soh_infer.c compiles against. The int8 weights stay int8 in flash;
they are dequantized one at a time during inference.

Usage:
  python edge/build_c_model.py outputs/edge_model_real_cell.json edge/soh_model.h
"""
import json
import sys
from pathlib import Path

LAYERS = ["W1", "b1", "W2", "b2", "Ws"]


def _f(v):
    # exponent form always has a '.', so the f suffix is valid (1f is not C)
    return f"{v:.9e}f"


def _floats(values):
    return ", ".join(_f(v) for v in values)


def build_header(model):
    n_in = len(model["features"])
    hidden = model["layers"]["b1"]["shape"][0]
    out = [
        "/* Generated by edge/build_c_model.py -- do not edit. */",
        "#ifndef SOH_MODEL_H",
        "#define SOH_MODEL_H",
        "#include <stdint.h>",
        "",
        f"#define SOH_N_FEATURES {n_in}",
        f"#define SOH_HIDDEN {hidden}",
        "",
        "/* input order: " + ", ".join(model["features"]) + " */",
        f"static const float SOH_MEAN[SOH_N_FEATURES] = {{{_floats(model['scaler_mean'])}}};",
        f"static const float SOH_STD[SOH_N_FEATURES] = {{{_floats(model['scaler_std'])}}};",
        "",
        "/* each layer: w = q * scale + min; row-major (in, out) */",
    ]
    for name in LAYERS:
        layer = model["layers"][name]
        q = ", ".join(str(v) for v in layer["q"])
        out.append(f"static const uint8_t SOH_{name}_Q[{len(layer['q'])}] = {{{q}}};")
        out.append(f"static const float SOH_{name}_MIN = {_f(layer['min'])};")
        out.append(f"static const float SOH_{name}_SCALE = {_f(layer['scale'])};")
    out += ["", "#endif", ""]
    return "\n".join(out)


def main(argv=None):
    argv = sys.argv[1:] if argv is None else argv
    if len(argv) != 2:
        raise SystemExit(__doc__)
    model = json.loads(Path(argv[0]).read_text())
    Path(argv[1]).write_text(build_header(model))
    print(f"wrote {argv[1]}")


if __name__ == "__main__":
    main()
